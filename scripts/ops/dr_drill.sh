#!/usr/bin/env bash
# Milestone 7: disaster-recovery restore drill. Restores RDS (point-in-time, latest restorable time) and the DynamoDB
# Slots table (PITR) into NEW resources, measures how long each restore takes, checks the restored data, writes the
# measurements to docs/dr-drill-<date>.md and deletes the drill copies. Production resources are never touched.
# Usage: ENVIRONMENT=dev AWS_REGION=ap-south-1 bash scripts/ops/dr_drill.sh
set -euo pipefail
ENVIRONMENT="${ENVIRONMENT:-dev}"
REGION="${AWS_REGION:-ap-south-1}"
STAMP="$(date -u +%Y%m%d%H%M)"
SRC_DB="medislot-${ENVIRONMENT}-mysql"
DRILL_DB="medislot-${ENVIRONMENT}-drill-${STAMP}"
SRC_TABLE="MediSlot-${ENVIRONMENT}-Slots"
DRILL_TABLE="MediSlot-${ENVIRONMENT}-Slots-drill-${STAMP}"
REPORT="docs/dr-drill-$(date -u +%Y-%m-%d).md"

subnets="$(aws rds describe-db-instances --db-instance-identifier "$SRC_DB" --region "$REGION" \
           --query 'DBInstances[0].DBSubnetGroup.DBSubnetGroupName' --output text)"
sgs="$(aws rds describe-db-instances --db-instance-identifier "$SRC_DB" --region "$REGION" \
       --query 'DBInstances[0].VpcSecurityGroups[*].VpcSecurityGroupId' --output text)"
latest="$(aws rds describe-db-instances --db-instance-identifier "$SRC_DB" --region "$REGION" \
          --query 'DBInstances[0].LatestRestorableTime' --output text)"

echo "== RDS point-in-time restore ($SRC_DB @ $latest -> $DRILL_DB)"
t0=$(date +%s)
aws rds restore-db-instance-to-point-in-time --source-db-instance-identifier "$SRC_DB" \
  --target-db-instance-identifier "$DRILL_DB" --use-latest-restorable-time --db-subnet-group-name "$subnets" \
  --vpc-security-group-ids $sgs --no-publicly-accessible --db-instance-class db.t3.micro --no-multi-az \
  --tags Key=Project,Value=MediSlot Key=Environment,Value="$ENVIRONMENT" Key=Purpose,Value=dr-drill \
  --region "$REGION" >/dev/null
aws rds wait db-instance-available --db-instance-identifier "$DRILL_DB" --region "$REGION"
t1=$(date +%s)
rds_secs=$((t1 - t0))
rds_status="$(aws rds describe-db-instances --db-instance-identifier "$DRILL_DB" --region "$REGION" --query 'DBInstances[0].DBInstanceStatus' --output text)"
echo "   restored in ${rds_secs}s (status: $rds_status)"

echo "== DynamoDB PITR restore ($SRC_TABLE -> $DRILL_TABLE)"
t2=$(date +%s)
aws dynamodb restore-table-to-point-in-time --source-table-name "$SRC_TABLE" --target-table-name "$DRILL_TABLE" \
  --use-latest-restorable-time --billing-mode-override PAY_PER_REQUEST --region "$REGION" >/dev/null
aws dynamodb wait table-exists --table-name "$DRILL_TABLE" --region "$REGION"
for _ in $(seq 1 180); do
  st="$(aws dynamodb describe-table --table-name "$DRILL_TABLE" --region "$REGION" --query Table.TableStatus --output text)"
  [[ "$st" == "ACTIVE" ]] && break
  sleep 10
done
t3=$(date +%s)
ddb_secs=$((t3 - t2))
src_items="$(aws dynamodb scan --table-name "$SRC_TABLE" --select COUNT --region "$REGION" --query Count --output text)"
drill_items="$(aws dynamodb scan --table-name "$DRILL_TABLE" --select COUNT --region "$REGION" --query Count --output text)"
echo "   restored in ${ddb_secs}s; items source=$src_items restored=$drill_items"

cat > "$REPORT" <<MD
# MediSlot DR restore drill - $(date -u +%Y-%m-%dT%H:%MZ)

Environment: \`$ENVIRONMENT\`, region \`$REGION\`. Generated by \`scripts/ops/dr_drill.sh\`.

| Store | Source | Restored copy | Method | Measured restore time | Check |
|---|---|---|---|---|---|
| RDS MySQL | \`$SRC_DB\` | \`$DRILL_DB\` | point-in-time, latest restorable time ($latest) | **${rds_secs} s** ($((rds_secs / 60)) min) | instance status \`$rds_status\` |
| DynamoDB Slots | \`$SRC_TABLE\` | \`$DRILL_TABLE\` | PITR, latest restorable time | **${ddb_secs} s** | items: source $src_items / restored $drill_items |

RPO: RDS automated backups keep transaction logs every 5 minutes (retention 1 day - the free-plan maximum); DynamoDB PITR is continuous
(35 days). RTO observed in this drill: the RDS restore above plus repointing \`/medislot/$ENVIRONMENT/db/host\` (SSM)
at the restored endpoint - the Lambdas read it at runtime, so no redeploy is needed.

The drill copies were deleted after the measurement.
MD
echo "== report written to $REPORT"

echo "== cleaning up drill copies"
aws rds delete-db-instance --db-instance-identifier "$DRILL_DB" --skip-final-snapshot --delete-automated-backups --region "$REGION" >/dev/null
aws dynamodb delete-table --table-name "$DRILL_TABLE" --region "$REGION" >/dev/null
echo "done: RDS ${rds_secs}s, DynamoDB ${ddb_secs}s"
